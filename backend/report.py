def render_plain_text(job_data, frames_meta):
    """Plain-text alternative of the report."""
    is_synthetic = bool(job_data.get("is_synthetic", False))
    return (
        f"SPHEREx Sky — Cutout Report ({'SYNTHETIC DEMO' if is_synthetic else 'NASA IRSA Level 2'})\n"
        f"Target: {job_data['target_name']}\n"
        f"Coordinates: RA {job_data['ra']:.4f} deg, Dec {job_data['dec']:+.4f} deg ({job_data['ra_hms']}, {job_data['dec_dms']})\n"
        f"IRSA Level 2 Frames Found: {job_data.get('total_irsa_hits', 0)}\n\n"
        + "\n".join(
            f"- Pass {fm['pass_num']}: {fm['d']} {fm['t']} UT | Obs {fm['obs_id']} | {fm['det']} ({fm['wl']:.2f} um) | Flux {fm['flux']:.2f} MJy/sr | Flag {fm.get('contam_flag', '0x00')}"
            for fm in frames_meta
        )
    )
